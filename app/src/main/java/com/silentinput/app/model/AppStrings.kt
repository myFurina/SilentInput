package com.silentinput.app.model

import java.util.Locale

enum class AppLanguage(val prefValue: String) {
    SYSTEM("system"),
    ZH("zh"),
    EN("en");

    companion object {
        fun fromPref(value: String?): AppLanguage {
            return values().firstOrNull { it.prefValue == value } ?: SYSTEM
        }
    }
}

enum class ResolvedLanguage {
    ZH,
    EN
}

object AppLocaleResolver {
    fun resolve(
        language: AppLanguage,
        systemLocale: Locale = Locale.getDefault()
    ): ResolvedLanguage {
        return when (language) {
            AppLanguage.ZH -> ResolvedLanguage.ZH
            AppLanguage.EN -> ResolvedLanguage.EN
            AppLanguage.SYSTEM -> {
                val lang = systemLocale.language.lowercase(Locale.ROOT)
                if (lang == "zh") ResolvedLanguage.ZH else ResolvedLanguage.EN
            }
        }
    }
}

